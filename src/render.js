export const MARKER = '<!-- agentic-pr-review -->';

const STATUS = { met: '✅ Met', partial: '🟡 Partial', missing: '❌ Missing', unclear: '❔ Unclear' };
const SEVERITY = { high: '🔴 High', medium: '🟠 Medium', low: '🟢 Low' };

const cell = (s = '') => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderComment(review, { model, skipped = [] } = {}) {
  const out = [MARKER, '## 🤖 Agentic PR review', '', review.summary, ''];

  if (review.requirements.length) {
    out.push('### Requirement coverage', '', '| Requirement | Status | Evidence |', '|---|---|---|');
    for (const r of review.requirements) {
      out.push(`| ${cell(r.requirement)} | ${STATUS[r.status] || cell(r.status)} | ${cell(r.evidence)} |`);
    }
    out.push('');
  }

  if (review.regressions.length) {
    out.push('### Possible regressions', '');
    for (const r of review.regressions) {
      out.push(`- ${SEVERITY[r.severity] || r.severity} ${r.risk}${r.file ? ` (\`${r.file}\`)` : ''}`);
    }
    out.push('');
  }

  if (review.conflicts.length) {
    out.push('### Overlap with other open PRs', '');
    for (const c of review.conflicts) out.push(`- #${c.pr}: ${c.note}`);
    out.push('');
  }

  if (review.questions.length) {
    out.push('### Questions for the author', '');
    for (const q of review.questions) out.push(`- ${q}`);
    out.push('');
  }

  if (skipped.length) out.push(`<sub>Not reviewed (size budget): ${skipped.join(', ')}</sub>`, '');
  out.push(`<sub>Generated by agentic-pr-review with ${model}. A human reviewer makes the final call.</sub>`);
  return out.join('\n');
}

// For the optional gate: does anything in the review meet the failure threshold?
export function shouldFail(review, failOn) {
  if (failOn === 'missing') return review.requirements.some((r) => r.status === 'missing');
  if (failOn === 'high') return review.regressions.some((r) => r.severity === 'high');
  return false;
}
